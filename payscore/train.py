"""Retrain the LightGBM baseline and write artifacts.

    python -m payscore.train                       # synthetic dev data, seed 42
    python -m payscore.train --source homecredit --homecredit-path /path/application_train.csv
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

import lightgbm as lgb
import numpy as np
import pandas as pd
import sklearn
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, brier_score_loss, log_loss, roc_auc_score, roc_curve
from sklearn.model_selection import train_test_split
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from . import __version__
from .features import CATEGORICAL, FEATURE_NAMES, build_features
from .homecredit import load_homecredit
from .model import DEFAULT_MODEL_DIR, META_FILE, MODEL_FILE
from .synthetic import generate

SYNTHETIC_NOTE = (
    "SYNTHETIC development data generated by payscore.synthetic. Metrics are pipeline-test numbers only "
    "and are NOT Home Credit benchmark results."
)


def _metrics(y: np.ndarray, p: np.ndarray) -> dict[str, float]:
    fpr, tpr, _ = roc_curve(y, p)
    return {
        "roc_auc": float(roc_auc_score(y, p)),
        "pr_auc": float(average_precision_score(y, p)),
        "log_loss": float(log_loss(y, p)),
        "brier": float(brier_score_loss(y, p)),
        "ks": float(np.max(tpr - fpr)),
        "positive_rate": float(np.mean(y)),
        "n": int(len(y)),
    }


def train(
    source: str = "synthetic",
    n_rows: int = 30_000,
    seed: int = 42,
    out_dir: Path | str = DEFAULT_MODEL_DIR,
    homecredit_path: Optional[str] = None,
    num_boost_round: int = 2000,
    early_stopping_rounds: int = 100,
    learning_rate: float = 0.03,
) -> dict[str, Any]:
    if source == "synthetic":
        df = generate(n_rows=n_rows, seed=seed)
        kind, note = "synthetic_development_dataset", SYNTHETIC_NOTE
    elif source == "homecredit":
        if not homecredit_path:
            raise ValueError("--homecredit-path is required for --source homecredit")
        df = load_homecredit(homecredit_path)
        kind, note = "homecredit", "Home Credit Default Risk application_train.csv (partial mapping, see homecredit.py)."
    else:
        raise ValueError(f"unknown source {source!r}")

    y = df["TARGET"].to_numpy()
    data_hash = hashlib.sha256(df.to_csv(index=False).encode()).hexdigest()

    # Reproducible stratified 70/15/15 split BEFORE any fitting (prevents leakage).
    idx = np.arange(len(df))
    train_idx, rest_idx = train_test_split(idx, test_size=0.30, stratify=y, random_state=seed)
    valid_idx, test_idx = train_test_split(rest_idx, test_size=0.50, stratify=y[rest_idx], random_state=seed)

    X = build_features(df)  # target column is never part of the features
    assert "TARGET" not in X.columns
    dtrain = lgb.Dataset(X.iloc[train_idx], y[train_idx], categorical_feature=CATEGORICAL, free_raw_data=False)
    dvalid = lgb.Dataset(X.iloc[valid_idx], y[valid_idx], reference=dtrain, categorical_feature=CATEGORICAL)
    params = {
        "objective": "binary", "metric": "auc", "learning_rate": learning_rate, "num_leaves": 31,
        "min_child_samples": 50, "feature_fraction": 0.8, "bagging_fraction": 0.8, "bagging_freq": 1,
        "lambda_l2": 1.0, "seed": seed, "deterministic": True, "force_row_wise": True,
        "num_threads": 1, "verbosity": -1,
    }
    booster = lgb.train(
        params, dtrain, num_boost_round=num_boost_round, valid_sets=[dvalid], valid_names=["valid"],
        callbacks=[lgb.early_stopping(early_stopping_rounds, verbose=False)],
    )
    best_iter = int(booster.best_iteration)

    metrics = {
        "train": _metrics(y[train_idx], booster.predict(X.iloc[train_idx], num_iteration=best_iter)),
        "valid": _metrics(y[valid_idx], booster.predict(X.iloc[valid_idx], num_iteration=best_iter)),
        "test": _metrics(y[test_idx], booster.predict(X.iloc[test_idx], num_iteration=best_iter)),
    }
    # Context baseline: median-imputed logistic regression, fitted on the training split only.
    logreg = make_pipeline(SimpleImputer(strategy="median", add_indicator=True), StandardScaler(),
                           LogisticRegression(max_iter=1000))
    logreg.fit(X.iloc[train_idx], y[train_idx])
    baseline_test = _metrics(y[test_idx], logreg.predict_proba(X.iloc[test_idx])[:, 1])

    gains = booster.feature_importance(importance_type="gain")
    importance = {n: round(float(g), 2) for n, g in sorted(zip(FEATURE_NAMES, gains, strict=False), key=lambda t: -t[1])}

    metadata = {
        "model_name": "payscore-lgbm-baseline",
        "model_version": f"{__version__}-{source}-seed{seed}",
        "trained_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "feature_names": FEATURE_NAMES,
        "categorical_features": CATEGORICAL,
        "missing_value_handling": "NaN passed natively to LightGBM; ratios are NaN when the denominator is missing or <= 0.",
        "training_data": {"kind": kind, "note": note, "n_rows": int(len(df)), "sha256": data_hash, "seed": seed,
                          "split": "stratified 70/15/15 train/valid/test, random_state=seed"},
        "lightgbm_params": params,
        "best_iteration": best_iter,
        "metrics": metrics,
        "baseline_logistic_regression_test": baseline_test,
        "feature_importance_gain": importance,
        "library_versions": {"lightgbm": lgb.__version__, "scikit-learn": sklearn.__version__,
                             "pandas": pd.__version__, "numpy": np.__version__},
        "caveat": note,
    }
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    booster.save_model(str(out / MODEL_FILE), num_iteration=best_iter)
    (out / META_FILE).write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    return metadata


def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", choices=["synthetic", "homecredit"], default="synthetic")
    ap.add_argument("--homecredit-path")
    ap.add_argument("--n-rows", type=int, default=30_000, help="synthetic rows (ignored for homecredit)")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out-dir", default=str(DEFAULT_MODEL_DIR))
    a = ap.parse_args(argv)
    try:
        md = train(a.source, a.n_rows, a.seed, a.out_dir, a.homecredit_path)
    except (ValueError, FileNotFoundError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    print(f"[{md['training_data']['kind']}] {md['training_data']['note']}")
    for split in ("train", "valid", "test"):
        m = md["metrics"][split]
        print(f"{split:5s} AUC={m['roc_auc']:.4f} PR-AUC={m['pr_auc']:.4f} KS={m['ks']:.4f} "
              f"logloss={m['log_loss']:.4f} brier={m['brier']:.4f} (n={m['n']})")
    print(f"baseline logistic regression test AUC={md['baseline_logistic_regression_test']['roc_auc']:.4f}")
    print(f"best_iteration={md['best_iteration']}  artifacts -> {a.out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
